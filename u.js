// ২. র ডেটাকে কাঙ্ক্ষিত mcq-block ফরম্যাটে রূপান্তর করা
const formattedQuestions = rawData.map((item) => {
  // options অবজেক্টকে অ্যারেতে রূপান্তর
  const optionsArray = [
    item.options.a,
    item.options.b,
    item.options.c,
    item.options.d
  ].filter(Boolean);

  // 'a', 'b', 'c', 'd' কে সংখ্যাসূচক সঠিক ইনডেক্সে রূপান্তর (0, 1, 2, 3)
  let correctIdx = 0;
  const opt = String(item.correct_option || "").toLowerCase().trim();
  if (opt === 'b') correctIdx = 1;
  else if (opt === 'c') correctIdx = 2;
  else if (opt === 'd') correctIdx = 3;

  return {
    id: item.id,
    question: item.question,
    options: optionsArray,
    correctIndex: correctIdx,
    explanation: item.explanation || "",
    tag: item.tag
  };
});

// ৩. ফাইনাল ব্লক স্ট্রাকচার তৈরি
